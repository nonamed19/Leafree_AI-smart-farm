/*
	RTC 알람 Callback - 특정 시간마다 Watering Task에 notify를 전달 하는 함수
*/
void HAL_RTC_AlarmAEventCallback(RTC_HandleTypeDef *hrtc)
{
		RTC_TimeTypeDef t;
		HAL_RTC_GetTime(hrtc, &t, RTC_FORMAT_BIN);

		BaseType_t hp = pdFALSE;

		// 워터링 Task Notify
		xTaskNotifyFromISR(xWateringTaskHandle, 0, eSetValueWithoutOverwrite, &hp);

		portYIELD_FROM_ISR(hp);
}

/*
	시간 단위로 RTC를 활용하여 알람을 걸어주는 함수
*/
void set_next_alarm_hours(uint32_t add_hours)
{
    RTC_TimeTypeDef t; RTC_DateTypeDef d;
    HAL_RTC_GetTime(&hrtc, &t, RTC_FORMAT_BIN);
    HAL_RTC_GetDate(&hrtc, &d, RTC_FORMAT_BIN);

    uint32_t total = t.Hours + add_hours;
    uint8_t  nextH = total % 24;
    uint8_t  carry = total / 24;

    d.Date = (d.Date + carry - 1) % 31 + 1;

    RTC_AlarmTypeDef a = {0};
    a.AlarmTime.Hours   = nextH;
    a.AlarmTime.Minutes = t.Minutes;
    a.AlarmTime.Seconds = t.Seconds;
    HAL_RTC_SetAlarm_IT(&hrtc, &a, RTC_FORMAT_BIN);
}

/*
	테스트용 RTC를 활용하여 알람을 걸어주는 함수
*/
void set_next_alarm_sec(uint32_t add_sec)
{
    RTC_TimeTypeDef t; RTC_DateTypeDef d;
    HAL_RTC_GetTime(&hrtc, &t, RTC_FORMAT_BIN);
    HAL_RTC_GetDate(&hrtc, &d, RTC_FORMAT_BIN);

    uint32_t sec  = t.Seconds + add_sec;
    uint32_t min  = t.Minutes + sec / 60;   sec %= 60;
    uint32_t hour = t.Hours   + min / 60;   min %= 60;
    hour %= 24;

    RTC_AlarmTypeDef a = {0};
    a.AlarmTime.Hours   = hour;
    a.AlarmTime.Minutes = min;
    a.AlarmTime.Seconds = sec;
    HAL_RTC_SetAlarm_IT(&hrtc, &a, RTC_FORMAT_BIN);
}

